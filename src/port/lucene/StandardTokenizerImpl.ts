  /** Current lexical state. */
  private zzLexicalState = StandardTokenizerImpl.YYINITIAL
  /** This buffer contains the current text to be matched and is the source of the yytext() string. */
  private zzBuffer = new Uint16Array(this.ZZ_BUFFERSIZE)
  /** Text position at the last accepting state. */
  private zzMarkedPos = 0
  /** Current text position in the buffer. */
  private zzCurrentPos = 0
  /** Marks the beginning of the yytext() string in the buffer. */
  private zzStartRead = 0
  /** Marks the last character in the buffer, that has been read from input. */
  private zzEndRead = 0
  /** Whether the scanner is at the end of file. */
  private zzAtEOF = false
  /** The number of occupied positions in zzBuffer beyond zzEndRead. */
  private zzFinalHighSurrogate = 0
  /** Number of characters up to the start of the matched text. */
  private yycharL = 0

  constructor(input: StringReader) {
    this.zzReader = input
  }

  /** Character count processed so far */
  yychar(): number {
    return this.yycharL
  }

  /** Fills CharTermAttribute with the current token text. */
  getText(t: CharTermAttribute): void {
    t.copyBuffer(this.zzBuffer, this.zzStartRead, this.zzMarkedPos - this.zzStartRead)
  }

  /** Sets the scanner buffer size in chars */
  setBufferSize(numChars: number): void {
    this.ZZ_BUFFERSIZE = numChars
    const newZzBuffer = new Uint16Array(this.ZZ_BUFFERSIZE)
    newZzBuffer.set(this.zzBuffer.subarray(0, Math.min(this.zzBuffer.length, this.ZZ_BUFFERSIZE)))
    this.zzBuffer = newZzBuffer
  }

  /** Refills the input buffer. @return false iff there was new input. */
  private zzRefill(): boolean {
    /* first: make room (if you can) */
    if (this.zzStartRead > 0) {
      this.zzEndRead += this.zzFinalHighSurrogate
      this.zzFinalHighSurrogate = 0
      this.zzBuffer.copyWithin(0, this.zzStartRead, this.zzEndRead)

      /* translate stored positions */
      this.zzEndRead -= this.zzStartRead
      this.zzCurrentPos -= this.zzStartRead
      this.zzMarkedPos -= this.zzStartRead
      this.zzStartRead = 0
    }

    /* fill the buffer with new input */
    const requested = this.zzBuffer.length - this.zzEndRead - this.zzFinalHighSurrogate
    if (requested === 0) {
      return true
    }
    const numRead = this.zzReader.readInto(this.zzBuffer, this.zzEndRead, requested)

    if (numRead > 0) {
      this.zzEndRead += numRead
      if (isHighSurrogate(this.zzBuffer[this.zzEndRead - 1] as number)) {
        if (numRead === requested) {
          // We requested too few chars to encode a full Unicode character
          --this.zzEndRead
          this.zzFinalHighSurrogate = 1
          if (numRead === 1) {
            return true
          }
        } else {
          // There is room in the buffer for at least one more char
          const c = this.zzReader.read() // Expecting to read a paired low surrogate char
          if (c === -1) {
            return true
          } else {
            this.zzBuffer[this.zzEndRead++] = c
          }
        }
      }
      /* potentially more input available */
      return false
    }

    /* numRead < 0 ==> end of stream */
    return true
  }

  /** Closes the input reader. */
  yyclose(): void {
    this.zzAtEOF = true // indicate end of file
    this.zzEndRead = this.zzStartRead // invalidate buffer
    this.zzReader.close()
  }

  /** Resets the scanner to read from a new input stream. */
  yyreset(reader: StringReader): void {
    this.zzReader = reader
    this.yyResetPosition()
    this.zzLexicalState = StandardTokenizerImpl.YYINITIAL
    if (this.zzBuffer.length > this.ZZ_BUFFERSIZE) {
      this.zzBuffer = new Uint16Array(this.ZZ_BUFFERSIZE)
    }
  }

  /** Resets the input position. */
  private yyResetPosition(): void {
    this.zzAtEOF = false
    this.zzCurrentPos = 0
    this.zzMarkedPos = 0
    this.zzStartRead = 0
    this.zzEndRead = 0
    this.zzFinalHighSurrogate = 0
    this.yycharL = 0
  }

  /** How many characters were matched. */
  yylength(): number {
    return this.zzMarkedPos - this.zzStartRead
  }

  private static zzScanError(errorCode: number): never {
    throw new Error(ZZ_ERROR_MSG[errorCode] ?? ZZ_ERROR_MSG[ZZ_UNKNOWN_ERROR])
  }

  yypushback(number: number): void {
    if (number > this.yylength()) StandardTokenizerImpl.zzScanError(ZZ_PUSHBACK_2BIG)
    this.zzMarkedPos -= number
  }

  /** Resumes scanning until the next regular expression is matched, the end of input is encountered. */
  getNextToken(): number {
    let zzInput: number
    let zzAction: number

    // cached fields:
    let zzCurrentPosL: number
    let zzMarkedPosL: number
    let zzEndReadL = this.zzEndRead
    let zzBufferL = this.zzBuffer

    const zzTransL = ZZ_TRANS
    const zzRowMapL = ZZ_ROWMAP
    const zzAttrL = ZZ_ATTRIBUTE

    while (true) {
      zzMarkedPosL = this.zzMarkedPos

      this.yycharL += zzMarkedPosL - this.zzStartRead

      zzAction = -1

      zzCurrentPosL = this.zzCurrentPos = this.zzStartRead = zzMarkedPosL

      this.zzState = ZZ_LEXSTATE[this.zzLexicalState] as number

      // set up zzAction for empty match case:
      let zzAttributes = zzAttrL[this.zzState] as number
      if ((zzAttributes & 1) === 1) {
        zzAction = this.zzState
      }

      zzForAction: {
        while (true) {
          if (zzCurrentPosL < zzEndReadL) {
            zzInput = codePointAt(zzBufferL, zzCurrentPosL, zzEndReadL)
            zzCurrentPosL += charCount(zzInput)
          } else if (this.zzAtEOF) {
            zzInput = StandardTokenizerImpl.YYEOF
            break zzForAction
          } else {
            // store back cached positions
            this.zzCurrentPos = zzCurrentPosL
            this.zzMarkedPos = zzMarkedPosL
            const eof = this.zzRefill()
            // get translated positions and possibly new buffer
            zzCurrentPosL = this.zzCurrentPos
            zzMarkedPosL = this.zzMarkedPos
            zzBufferL = this.zzBuffer
            zzEndReadL = this.zzEndRead
            if (eof) {
              zzInput = StandardTokenizerImpl.YYEOF
              break zzForAction
            } else {
              zzInput = codePointAt(zzBufferL, zzCurrentPosL, zzEndReadL)
              zzCurrentPosL += charCount(zzInput)
            }
          }
          const zzNext = zzTransL[(zzRowMapL[this.zzState] as number) + zzCMap(zzInput)] as number
          if (zzNext === -1) break zzForAction
          this.zzState = zzNext

          zzAttributes = zzAttrL[this.zzState] as number
          if ((zzAttributes & 1) === 1) {
            zzAction = this.zzState
            zzMarkedPosL = zzCurrentPosL
            if ((zzAttributes & 8) === 8) break zzForAction
          }
        }
      }

      // store back cached position
      this.zzMarkedPos = zzMarkedPosL

      if (zzInput === StandardTokenizerImpl.YYEOF && this.zzStartRead === this.zzCurrentPos) {
        this.zzAtEOF = true
        return StandardTokenizerImpl.YYEOF
      } else {
        switch (zzAction < 0 ? zzAction : (ZZ_ACTION[zzAction] as number)) {
          case 1:
            /* Not numeric, word, ideographic, hiragana, emoji or SE Asian -- ignore it. */
            break
          case 10:
            break
          case 2:
            return StandardTokenizerImpl.NUMERIC_TYPE
          case 11:
            break
          case 3:
            return StandardTokenizerImpl.WORD_TYPE
          case 12:
            break
          case 4:
            return StandardTokenizerImpl.EMOJI_TYPE
          case 13:
            break
          case 5:
            return StandardTokenizerImpl.SOUTH_EAST_ASIAN_TYPE
          case 14:
            break
          case 6:
            return StandardTokenizerImpl.HANGUL_TYPE
          case 15:
            break
          case 7:
            return StandardTokenizerImpl.IDEOGRAPHIC_TYPE
          case 16:
            break
          case 8:
            return StandardTokenizerImpl.KATAKANA_TYPE
          case 17:
            break
          case 9:
            return StandardTokenizerImpl.HIRAGANA_TYPE
          case 18:
            break
          default:
            StandardTokenizerImpl.zzScanError(ZZ_NO_MATCH)
        }
      }
    }
  }
