function zzUnpackRuns(packed: string, size: number, minus: number): Int32Array {
  const result = new Int32Array(size)
  let i = 0 /* index in packed string  */
  let j = 0 /* index in unpacked array */
  const l = packed.length
  while (i < l) {
    let count = packed.charCodeAt(i++)
    const value = packed.charCodeAt(i++) - minus
    do result[j++] = value
    while (--count > 0)
  }
  return result
}

function zzUnpackRowMap(packed: string, size: number): Int32Array {
  const result = new Int32Array(size)
  let i = 0 /* index in packed string  */
  let j = 0 /* index in unpacked array */
  const l = packed.length
  while (i < l) {
    const high = packed.charCodeAt(i++) << 16
    result[j++] = high | packed.charCodeAt(i++)
  }
  return result
}

/** Top-level table for translating characters to character classes */
const ZZ_CMAP_TOP = zzUnpackRuns(ZZ_CMAP_TOP_PACKED_0, 4352, 0)
/** Second-level tables for translating characters to character classes */
const ZZ_CMAP_BLOCKS = zzUnpackRuns(ZZ_CMAP_BLOCKS_PACKED_0, 35328, 0)
/** Translates DFA states to action switch labels. */
const ZZ_ACTION = zzUnpackRuns(ZZ_ACTION_PACKED_0, 59, 0)
/** Translates a state to a row index in the transition table */
const ZZ_ROWMAP = zzUnpackRowMap(ZZ_ROWMAP_PACKED_0, 59)
