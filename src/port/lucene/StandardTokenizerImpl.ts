const ZZ_TRANS = zzUnpackRuns(ZZ_TRANS_PACKED_0, 1537, 1)
/** ZZ_ATTRIBUTE[aState] contains the attributes of state aState */
const ZZ_ATTRIBUTE = zzUnpackRuns(ZZ_ATTRIBUTE_PACKED_0, 59, 0)

